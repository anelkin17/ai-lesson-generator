import os
from openai import OpenAI


def generate_lesson(
    subject,
    grade,
    topic,
    language,
    lesson_type,
    difficulty
):
    api_key = os.getenv("OPENAI_API_KEY")

    if not api_key:
        raise ValueError(
            "OPENAI_API_KEY не найден. "
            "Добавьте API ключ в переменные окружения."
        )

    client = OpenAI(api_key=api_key)

    prompt = f"""
Ты — профессиональный методист и AI-помощник преподавателя.

Создай качественный учебный материал.

Предмет: {subject}
Класс / курс: {grade}
Тема: {topic}
Язык: {language}
Тип материала: {lesson_type}
Уровень сложности: {difficulty}

Требования:

1. Материал должен соответствовать указанному классу/курсу.
2. Используй понятный и педагогически грамотный язык.
3. Информация должна быть структурированной.
4. Добавь практическую часть, если это уместно.
5. Не используй непроверенные факты.
6. Сделай материал удобным для непосредственного использования преподавателем.

Если выбран тип "План урока", создай:

- тему урока;
- цели обучения;
- ожидаемые результаты;
- организационный этап;
- актуализацию знаний;
- объяснение нового материала;
- практическую работу;
- закрепление;
- оценивание;
- рефлексию;
- домашнее задание.

Если выбран тип "Тест", создай 10 вопросов.
Для каждого вопроса дай 4 варианта ответа.
После вопросов укажи правильные ответы.

Если выбран тип "Практическое задание", создай:
- цель;
- инструкцию;
- пошаговое выполнение;
- критерии оценивания;
- ожидаемый результат.

Если выбран тип "Домашнее задание", создай несколько заданий разного уровня сложности.

Если выбран тип "Критерии оценивания", создай понятную таблицу критериев и дескрипторов.

Ответ должен быть готов для использования преподавателем.
"""

    response = client.responses.create(
        model="gpt-5",
        input=prompt
    )

    return response.output_text
